_TRANSLATIONS = {"en": _ENGLISH, "uk": _UKRAINIAN}


def normalize_language(value: object) -> Language:
    return value if value in SUPPORTED_LANGUAGES else "en"


def tr(language: Language, key: str) -> str:
    return _TRANSLATIONS[language].get(key, _ENGLISH.get(key, key))
